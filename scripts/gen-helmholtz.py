#!/usr/bin/env python3
"""
Round 12b — reference (multiparameter Helmholtz) equations of state for pure fluids: writes api/_lib/mb-helmholtz.js.

Coefficients are read from CoolProp (MIT licence; the coefficients are those of the original publications):
  NH3  Gao, Wu, Lemmon et al., J. Phys. Chem. Ref. Data 49 (2020) 043103        CO2  Span & Wagner, JPCRD 25 (1996) 1509
  N2   Span, Lemmon, Jacobsen, Wagner & Yokozeki, JPCRD 29 (2000) 1361          H2   Leachman et al., JPCRD 38 (2009) 721 (normal)
  CH4  Setzmann & Wagner, JPCRD 20 (1991) 1061                                  Ar   Tegeler, Span & Wagner, JPCRD 28 (1999) 779
  O2   Schmidt & Wagner, Fluid Phase Equilib. 19 (1985) 175 (Stewart et al. 1991 form)
Term types handled: residual power (with exp(−δ^l)), Gaussian bell-shaped, the Gao "B" terms of ammonia and the
Span–Wagner non-analytic critical terms of CO2; ideal-gas ln δ, a ln τ, Planck–Einstein and power terms (the
constant and linear-in-τ ideal terms only fix the reference state, which the engine sets itself).

Usage (repo root):  pip install CoolProp ;  python3 scripts/gen-helmholtz.py
"""
import json, os, sys
import CoolProp
import CoolProp.CoolProp as CP

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'api/_lib/mb-helmholtz.js')
FLUIDS = [('NH3', 'Ammonia', 'Gao, Wu, Lemmon et al., J. Phys. Chem. Ref. Data 49 (2020) 043103'),
          ('CO2', 'CarbonDioxide', 'Span & Wagner, J. Phys. Chem. Ref. Data 25 (1996) 1509'),
          ('N2', 'Nitrogen', 'Span, Lemmon, Jacobsen, Wagner & Yokozeki, J. Phys. Chem. Ref. Data 29 (2000) 1361'),
          ('H2', 'Hydrogen', 'Leachman, Jacobsen, Penoncello & Lemmon, J. Phys. Chem. Ref. Data 38 (2009) 721 (normal hydrogen)'),
          ('CH4', 'Methane', 'Setzmann & Wagner, J. Phys. Chem. Ref. Data 20 (1991) 1061'),
          ('Ar', 'Argon', 'Tegeler, Span & Wagner, J. Phys. Chem. Ref. Data 28 (1999) 779'),
          ('O2', 'Oxygen', 'Schmidt & Wagner, Fluid Phase Equilib. 19 (1985) 175; Stewart, Jacobsen & Wagner, J. Phys. Chem. Ref. Data 20 (1991) 917')]

def terms(eos):
    res, ideal = [], []
    for t in eos['alphar']:
        ty = t['type']
        if ty == 'ResidualHelmholtzPower':
            for n, d, tt, l in zip(t['n'], t['d'], t['t'], t['l']): res.append(['p', n, d, tt, l])
        elif ty == 'ResidualHelmholtzGaussian':
            for n, d, tt, eta, eps, beta, gam in zip(t['n'], t['d'], t['t'], t['eta'], t['epsilon'], t['beta'], t['gamma']): res.append(['g', n, d, tt, eta, eps, beta, gam])
        elif ty == 'ResidualHelmholtzGaoB':
            for n, d, tt, eta, eps, beta, gam, b in zip(t['n'], t['d'], t['t'], t['eta'], t['epsilon'], t['beta'], t['gamma'], t['b']): res.append(['b', n, d, tt, eta, eps, beta, gam, b])
        elif ty == 'ResidualHelmholtzNonAnalytic':
            for n, a, b, beta, A, B, C, D in zip(t['n'], t['a'], t['b'], t['beta'], t['A'], t['B'], t['C'], t['D']): res.append(['na', n, a, b, beta, A, B, C, D])
        else: raise SystemExit('unhandled residual term ' + ty)
    Tr = eos['STATES']['reducing']['T']
    for t in eos['alpha0']:
        ty = t['type']
        if ty in ('IdealGasHelmholtzLead', 'IdealGasHelmholtzEnthalpyEntropyOffset'): continue      # reference state only
        if ty == 'IdealGasHelmholtzLogTau': ideal.append(['log', t['a']])
        elif ty == 'IdealGasHelmholtzPlanckEinstein':
            for n, tt in zip(t['n'], t['t']): ideal.append(['pe', n, tt])
        elif ty == 'IdealGasHelmholtzPlanckEinsteinFunctionT':
            for n, v in zip(t['n'], t['v']): ideal.append(['pe', n, v / Tr])
        elif ty == 'IdealGasHelmholtzPower':
            for n, tt in zip(t['n'], t['t']): ideal.append(['pow', n, tt])
        else: raise SystemExit('unhandled ideal term ' + ty)
    return res, ideal

data = {}
for key, name, ref in FLUIDS:
    j = json.loads(CP.get_fluid_param_string(name, 'JSON')); j = j[0] if isinstance(j, list) else j
    eos = j['EOS'][0]
    red = eos['STATES']['reducing']
    res, ideal = terms(eos)
    data[key] = {'name': name, 'ref': ref, 'R': eos['gas_constant'], 'M': eos['molar_mass'] * 1000, 'Tc': red['T'], 'rhoc': red['rhomolar'], 'pc': red['p'],
                 'Ttriple': eos['Ttriple'], 'Tmax': eos['T_max'], 'pmax': eos['p_max'], 'res': res, 'ideal': ideal}

JS = r'''// ============================================================================
// REPO PATH: api/_lib/mb-helmholtz.js
// ============================================================================
// multicalci.com — GENERATED by scripts/gen-helmholtz.py. Do not edit by hand.
// Reference equations of state (multiparameter Helmholtz energy) for pure
// NH3, CO2, N2, H2, CH4, Ar and O2 — coefficients of the original publications
// (listed per fluid below) as distributed with CoolProp @@CPVER@@ (MIT licence,
// Bell et al., Ind. Eng. Chem. Res. 53 (2014) 2498). Evaluator written for the
// engine: α = α° + αʳ with derivatives in τ = Tc/T and δ = ρ/ρc; density from
// (T, P) on the requested branch; properties of one phase. Server-side only.
// ============================================================================
export const HELMHOLTZ_VERSION = 'reference EOS r12 (CoolProp @@CPVER@@ coefficients)';
export const FLUIDS = @@DATA@@;

/** residual part: [a, a_d, a_dd, a_t, a_tt, a_dt] (plain partial derivatives in δ, τ) */
function residual(f, tau, del) {
  let a = 0, ad = 0, add = 0, at = 0, att = 0, adt = 0;
  for (const q of f.res) {
    const k = q[0];
    if (k === 'na') { const r = nonAnalytic(q, tau, del); a += r[0]; ad += r[1]; add += r[2]; at += r[3]; att += r[4]; adt += r[5]; continue; }
    const n = q[1], d = q[2], t = q[3];
    // n δ^d τ^t e^g with g(δ, τ) by term type
    let g = 0, gd = 0, gdd = 0, gt = 0, gtt = 0;
    if (k === 'p') {
      const l = q[4];
      if (l > 0) { const dl = Math.pow(del, l); g = -dl; gd = -l * dl / del; gdd = -l * (l - 1) * dl / (del * del); }
    } else if (k === 'g') {
      const eta = q[4], eps = q[5], beta = q[6], gam = q[7];
      g = -eta * (del - eps) ** 2 - beta * (tau - gam) ** 2; gd = -2 * eta * (del - eps); gdd = -2 * eta; gt = -2 * beta * (tau - gam); gtt = -2 * beta;
    } else if (k === 'b') {
      const eta = q[4], eps = q[5], beta = q[6], gam = q[7], b = q[8];
      const u = beta * (tau - gam) ** 2 + b, ut = 2 * beta * (tau - gam);
      g = eta * (del - eps) ** 2 + 1 / u; gd = 2 * eta * (del - eps); gdd = 2 * eta; gt = -ut / (u * u); gtt = -2 * beta / (u * u) + 2 * ut * ut / (u * u * u);   // η < 0 in Gao et al.
    }
    const v = n * Math.pow(del, d) * Math.pow(tau, t) * Math.exp(g);
    const Dd = d / del + gd, Dt = t / tau + gt;
    a += v; ad += v * Dd; add += v * (Dd * Dd - d / (del * del) + gdd);
    at += v * Dt; att += v * (Dt * Dt - t / (tau * tau) + gtt); adt += v * Dd * Dt;
  }
  return [a, ad, add, at, att, adt];
}

/** Span–Wagner non-analytic term n Δ^b δ ψ and its derivatives (IAPWS-95 formulation) */
function nonAnalytic(q, tau, delIn) {
  const [, n, a, b, beta, A, B, C, D] = q;
  const del = Math.abs(delIn - 1) < 1e-10 ? 1 + 1e-10 : delIn;
  const dm = del - 1, dm2 = dm * dm;
  const theta = (1 - tau) + A * Math.pow(dm2, 1 / (2 * beta));
  const Dl = theta * theta + B * Math.pow(dm2, a);
  const psi = Math.exp(-C * dm2 - D * (tau - 1) ** 2);
  const psid = -2 * C * dm * psi, psidd = (2 * C * dm2 - 1) * 2 * C * psi;
  const psit = -2 * D * (tau - 1) * psi, psitt = (2 * D * (tau - 1) ** 2 - 1) * 2 * D * psi, psidt = 4 * C * D * dm * (tau - 1) * psi;
  const dDd = dm * (A * theta * 2 / beta * Math.pow(dm2, 1 / (2 * beta) - 1) + 2 * B * a * Math.pow(dm2, a - 1));
  const dDdd = dDd / dm + dm2 * (4 * B * a * (a - 1) * Math.pow(dm2, a - 2) + 2 * A * A / (beta * beta) * Math.pow(Math.pow(dm2, 1 / (2 * beta) - 1), 2) +
    A * theta * 4 / beta * (1 / (2 * beta) - 1) * Math.pow(dm2, 1 / (2 * beta) - 2));
  const Db = Math.pow(Dl, b), Db1 = b * Math.pow(Dl, b - 1), Db2 = b * (b - 1) * Math.pow(Dl, b - 2);
  const Dbd = Db1 * dDd, Dbdd = Db1 * dDdd + Db2 * dDd * dDd;
  const Dbt = -2 * theta * Db1, Dbtt = 2 * Db1 + 4 * theta * theta * Db2;
  const Dbdt = -A * Db1 * 2 / beta * dm * Math.pow(dm2, 1 / (2 * beta) - 1) - 2 * theta * Db2 * dDd;
  return [n * Db * del * psi,
    n * (Db * (psi + del * psid) + Dbd * del * psi),
    n * (Db * (2 * psid + del * psidd) + 2 * Dbd * (psi + del * psid) + Dbdd * del * psi),
    n * del * (Dbt * psi + Db * psit),
    n * del * (Dbtt * psi + 2 * Dbt * psit + Db * psitt),
    n * (Db * (psit + del * psidt) + del * Dbd * psit + Dbt * (psi + del * psid) + Dbdt * del * psi)];
}

/** ideal part without the reference-state constants: [a0, a0_t, a0_tt] (ln δ included in a0) */
function ideal(f, tau, del) {
  let a = Math.log(del), at = 0, att = 0;
  for (const q of f.ideal) {
    if (q[0] === 'log') { a += q[1] * Math.log(tau); at += q[1] / tau; att -= q[1] / (tau * tau); }
    else if (q[0] === 'pe') { const n = q[1], t = q[2], e = Math.exp(-t * tau); a += n * Math.log(1 - e); at += n * t * e / (1 - e); att -= n * t * t * e / ((1 - e) * (1 - e)); }
    else if (q[0] === 'pow') { const n = q[1], t = q[2]; a += n * Math.pow(tau, t); at += n * t * Math.pow(tau, t - 1); att += n * t * (t - 1) * Math.pow(tau, t - 2); }
  }
  return [a, at, att];
}

export function fluid(key) { return FLUIDS[key] || null; }

/** pressure [Pa] and dP/dρ at T [K], ρ [mol/m³] */
export function pressure(f, T, rho) {
  const tau = f.Tc / T, del = rho / f.rhoc, r = residual(f, tau, del);
  return { P: rho * f.R * T * (1 + del * r[1]), dPdrho: f.R * T * (1 + 2 * del * r[1] + del * del * r[2]), r };
}

/**
 * density [mol/m³] at T [K], P [Pa] on the branch 'L' or 'V'. Newton in ρ approaches the root monotonically from
 * the side where it cannot overshoot — from above on the (convex) liquid branch, from the ideal-gas density on the
 * (concave) vapour branch; null when the branch has no root (beyond its spinodal).
 */
export function densityTP(f, T, P, phase, rho0) {
  if (phase === 'L') {
    let rho = Math.max(rho0 > 0 ? rho0 * 1.05 : 0, 2.2 * f.rhoc);
    for (let k = 0; k < 60 && !(pressure(f, T, rho).P > P); k++) rho *= 1.05;
    for (let it = 0; it < 200; it++) {
      const q = pressure(f, T, rho);
      if (!(q.dPdrho > 0)) return null;
      const step = (q.P - P) / q.dPdrho;
      rho -= step;
      if (Math.abs(step) < 1e-12 * rho) return rho > f.rhoc * 0.25 ? rho : null;
    }
    return null;
  }
  let rho = rho0 > 0 ? Math.min(rho0, P / (f.R * T)) : P / (f.R * T);
  for (let k = 0; k < 60 && !(pressure(f, T, rho).P < P); k++) rho *= 0.9;
  for (let it = 0; it < 200; it++) {
    const q = pressure(f, T, rho);
    if (!(q.dPdrho > 0)) return null;
    const step = (P - q.P) / q.dPdrho;
    rho += step;
    if (!(rho > 0)) return null;
    if (Math.abs(step) < 1e-12 * rho) return rho;
  }
  return null;
}

/** one-phase properties at T [K], ρ [mol/m³]; h, s without the reference-state constants */
export function stateTrho(f, T, rho) {
  const tau = f.Tc / T, del = rho / f.rhoc, R = f.R;
  const r = residual(f, tau, del), o = ideal(f, tau, del);
  const Z = 1 + del * r[1];
  const P = rho * R * T * Z;
  const hres = R * T * (tau * r[3] + del * r[1]), sresTrho = R * (tau * r[3] - r[0]);
  const cv = -R * tau * tau * (o[2] + r[4]);
  const num = 1 + del * r[1] - del * tau * r[5], den = 1 + 2 * del * r[1] + del * del * r[2];
  const cp = cv + R * num * num / den;
  const w2 = R * T / (f.M / 1000) * (den - num * num / (tau * tau * (o[2] + r[4])));
  return { T, rho, P, Z, hres, sres: sresTrho + R * Math.log(Z), lnphi: r[0] + del * r[1] - Math.log(Z), cp, cv, w: Math.sqrt(Math.max(w2, 0)),
    // ideal-gas h and s(T, 101325 Pa) on the equation's own (unanchored) basis
    hig: R * T * (1 + tau * o[1]), dPdrho: R * T * den };
}

/** ideal-gas enthalpy [J/mol] and entropy at 101325 Pa [J/(mol K)], unanchored */
export function idealGas(f, T) {
  const tau = f.Tc / T, rho = 101325 / (f.R * T), o = ideal(f, tau, rho / f.rhoc);
  return { h: f.R * T * (1 + tau * o[1]), s: f.R * (tau * o[1] - o[0]) };
}

export default { HELMHOLTZ_VERSION, FLUIDS, fluid, pressure, densityTP, stateTrho, idealGas };
'''
open(OUT, 'w').write(JS.replace('@@DATA@@', json.dumps(data, separators=(',', ':'))).replace('@@CPVER@@', CoolProp.__version__))
print('wrote', OUT, ', '.join(data))
