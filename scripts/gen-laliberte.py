# multicalci.com — STEP 38: density, viscosity and heat-capacity coefficients of
# aqueous salts from M. Laliberté, J. Chem. Eng. Data 54 (2009) 1725 (and 52
# (2007) 321, 49 (2004) 1141), as tabulated in the open-source thermo library
# (C. Bell, MIT licence). Run from the repository root:  python3 scripts/gen-laliberte.py
# writes api/_lib/mb-laliberte.js (density range Tmin/Tmax/wmax, viscosity vT…, heat capacity cT…; °C, mass fraction)
# ============================================================================
import json
from thermo import electrochem as e
SALTS = ['NaCl', 'KCl', 'CaCl2', 'MgCl2', 'Na2SO4', 'K2SO4', 'MgSO4', 'CaSO4', 'NaOH', 'KOH', 'Na2CO3', 'NaHCO3', 'K2CO3', 'KHCO3', 'H2SO4', 'HCl']
d = e.Laliberte_data
out = {}
for s in SALTS:
    r = d[d['Formula'] == s].iloc[0]
    f = lambda k: (None if r[k] != r[k] else float(r[k]))
    out[s] = {'cas': r.name, 'mw': f('MW'), 'c': [f('c%d' % i) for i in range(5)], 'v': [f('v%d' % i) for i in range(1, 7)], 'a': [f('a%d' % i) for i in range(1, 7)],
              'Tmin': f('Min T'), 'Tmax': f('Max T'), 'wmax': f('Max w'), 'vTmin': f('Min T.1'), 'vTmax': f('Max T.1'), 'vwmax': f('Max w.1'),
              'cTmin': f('Min T.2'), 'cTmax': f('Max T.2'), 'cwmax': f('Max w.2')}
js = ('// GENERATED by scripts/gen-laliberte.py — Laliberté (2009) density / viscosity / heat-capacity coefficients\n'
      '// of aqueous salts, as tabulated in the thermo library (MIT licence). Do not edit by hand.\n'
      'export const LALIBERTE = ' + json.dumps(out, indent=0) + ';\nexport default LALIBERTE;\n')
open('api/_lib/mb-laliberte.js', 'w').write(js)
print({k: (v['c'][0] is not None, v['v'][0] is not None, v['a'][0] is not None) for k, v in out.items()})
