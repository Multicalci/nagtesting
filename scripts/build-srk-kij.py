#!/usr/bin/env python3
"""
Round 11 — SRK binary interaction parameters, separate from the Peng–Robinson table.

Reads ChemSep's srk.ipd (DECHEMA Soave–Redlich–Kwong parameters, Copyright Harry Kooijman and Ross Taylor,
Artistic License 2.0; the file ships with ChemSep and in DWSIM's Assets/ChemSepIPD folder) and writes
api/_lib/mb-bip-srk.js.

The DECHEMA library often lists several k_ij for one pair, fitted to different data sets — some at cryogenic
temperatures, a few far from the rest (CO2–ethane −0.009 beside five values near 0.133). Rule, per pair:
  1. the median of the sets whose temperature range reaches 250–450 K (process conditions);
  2. if none, the median of the sets that give no temperature;
  3. if the only sets lie outside 250–450 K, the ChemSep Peng–Robinson value of the pair when there is one
     (that library was curated in 2009), otherwise the median of all sets.
Pairs with no SRK entry use the Peng–Robinson value in the engine.

Usage (repo root):  python3 scripts/build-srk-kij.py path/to/srk.ipd
Standard library only.
"""
import json, os, re, statistics, sys
from collections import OrderedDict

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
LO, HI = 250.0, 450.0

def js_object(path, name):
    s = open(path, encoding='utf8').read()
    i = s.index('const ' + name + ' = ') + len('const ' + name + ' = ')
    return json.JSONDecoder().raw_decode(s, i)[0]

def trange(c):
    m = re.search(r'T\s*=\s*([\d.]+)\s*(?:-\s*([\d.]+)|,\s*([\d.]+))?\s*K?', c)
    if not m: return None
    a = float(m.group(1)); b = float(m.group(2) or m.group(3) or a)
    return (min(a, b), max(a, b))

def page(c):
    m = re.search(r'\bp(\d+)\b', c)
    return 'p' + m.group(1) if m else ''

def main(ipd):
    comps = js_object(os.path.join(ROOT, 'api/_lib/mb-compdb.js'), 'COMPS')
    cas = {}
    for k, c in comps.items():
        if c.get('cas'): cas.setdefault(c['cas'], k)
    pr = js_object(os.path.join(ROOT, 'api/_lib/mb-bip.js'), 'PR')
    rows = []
    for line in open(ipd, encoding='latin-1'):
        m = re.match(r'^\s*(\d+-\d+-\d)\s+(\d+-\d+-\d)\s+([-+.\deE]+)\s*(.*)$', line)
        if m: rows.append((m.group(1), m.group(2), float(m.group(3)), m.group(4).strip()))
    pairs = OrderedDict()
    for a, b, k, c in rows:
        if a in cas and b in cas and a != b:
            key = '|'.join(sorted((cas[a], cas[b])))
            pairs.setdefault(key, []).append((k, c))
    table, note = OrderedDict(), OrderedDict()
    for key in sorted(pairs):
        sets = pairs[key]
        rng = [(k, trange(c), page(c)) for k, c in sets]
        inwin = [(k, r, p) for k, r, p in rng if r and r[1] >= LO and r[0] <= HI]
        noT = [(k, r, p) for k, r, p in rng if r is None]
        if inwin:
            v = statistics.median([k for k, _, _ in inwin])
            lo = min(r[0] for _, r, _ in inwin); hi = max(r[1] for _, r, _ in inwin)
            how = (f'DECHEMA {inwin[0][2]}, {lo:g}–{hi:g} K' if len(inwin) == 1 else f'median of {len(inwin)} DECHEMA sets, {lo:g}–{hi:g} K')
        elif noT:
            v = statistics.median([k for k, _, _ in noT])
            how = f'DECHEMA {noT[0][2]}' if len(noT) == 1 else f'median of {len(noT)} DECHEMA sets'
        elif key in pr:
            v = pr[key]
            how = f'Peng–Robinson value — the {len(sets)} DECHEMA SRK set{"s" if len(sets) > 1 else ""} lie{"" if len(sets) > 1 else "s"} below {LO:g} K or above {HI:g} K'
        else:
            v = statistics.median([k for k, _, _ in rng])
            how = f'median of {len(sets)} DECHEMA sets outside {LO:g}–{HI:g} K'
        table[key] = round(v, 6); note[key] = how
    head = f"""// ============================================================================
// REPO PATH: api/_lib/mb-bip-srk.js
// ============================================================================
// multicalci.com — GENERATED by scripts/build-srk-kij.py. Do not edit by hand.
// Soave–Redlich–Kwong binary interaction parameters k_ij, separate from the
// Peng–Robinson table in mb-bip.js. Source: ChemSep v8.32 srk.ipd — DECHEMA
// Soave–Redlich–Kwong parameters (library by J. A. Clark, 2014), Copyright (c)
// Harry Kooijman and Ross Taylor, distributed under the Artistic License 2.0
// (http://www.perlfoundation.org/artistic_license_2_0) — values unchanged; where
// the library lists several sets for one pair, the median of those whose
// temperature range reaches {LO:g}–{HI:g} K is taken (see the script for the rule).
// Pairs absent here use the Peng–Robinson value. Keys sorted alphabetically 'a|b'.
// {len(rows)} library entries → {len(table)} pairs of databank components.
// Server-side only (api/_lib).
// ============================================================================
"""
    body = ("export const SRK_VERSION = " + json.dumps(f'mb-bip-srk 1.0.0 (ChemSep srk.ipd, {len(table)} pairs)') + ";\n"
            + "export const SRK = " + json.dumps(table, separators=(',', ':')) + ";\n"
            + "export const SRK_NOTE = " + json.dumps(note, ensure_ascii=False, separators=(',', ':')) + ";\n"
            + "export default { SRK_VERSION, SRK, SRK_NOTE };\n")
    out = os.path.join(ROOT, 'api/_lib/mb-bip-srk.js')
    open(out, 'w', encoding='utf8').write(head + body)
    print('wrote', out, len(table), 'pairs')

if __name__ == '__main__':
    if len(sys.argv) < 2: sys.exit('usage: build-srk-kij.py path/to/srk.ipd')
    main(sys.argv[1])
